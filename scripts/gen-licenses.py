#!/usr/bin/env python3
"""Write one text file with the licence text and copyright notices of every dependency that ends up in the release
binaries (R6 of docs/audit/assets-licences.md).

    scripts/gen-licenses.py [--target TRIPLE] [--out FILE]

Reads `cargo metadata` (needs the crates already downloaded, as after a build), and for every package of the target's
dependency graph that is not part of this workspace copies the files named LICENSE*, COPYING*, NOTICE*, UNLICENSE* and
AUTHORS* from the package directory. A package with a licence expression but none of those files is listed under
"No licence file shipped" so the gap is visible instead of hidden. Only the standard library is used.
"""
import argparse, json, os, subprocess, sys

PATTERNS = ("license", "licence", "copying", "notice", "unlicense", "authors", "copyright")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", help="target triple (default: host)")
    ap.add_argument("--out", default="LICENSES-DEPENDENCIES.txt")
    a = ap.parse_args()
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked"]
    if a.target:
        cmd += ["--filter-platform", a.target]
    meta = json.loads(subprocess.check_output(cmd))
    ws = set(meta["workspace_members"])
    pk = {p["id"]: p for p in meta["packages"]}
    used = {n["id"] for n in meta["resolve"]["nodes"]}
    rows, missing = [], []
    for pid in sorted(used - ws, key=lambda i: (pk[i]["name"], pk[i]["version"])):
        p = pk[pid]
        d = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(d)
                       if os.path.isfile(os.path.join(d, f)) and f.lower().startswith(PATTERNS))
        # crates keep licences in a few other places too
        fd = os.path.join(d, "fonts")        # epaint_default_fonts keeps the notices of the GUI fonts here
        if os.path.isdir(fd):
            files += [os.path.join("fonts", f) for f in sorted(os.listdir(fd))
                      if f.lower().endswith(".txt") and os.path.isfile(os.path.join(fd, f))]
        for sub in ("licenses", "license", "LICENSES"):
            sd = os.path.join(d, sub)
            if os.path.isdir(sd):
                files += [os.path.join(sub, f) for f in sorted(os.listdir(sd)) if os.path.isfile(os.path.join(sd, f))]
        rows.append((p, d, files))
        if not files:
            missing.append(p)
    with open(a.out, "w", encoding="utf-8") as o:
        o.write("LegatorOCR - licences of the Rust crates compiled into this program\n")
        o.write("Generated by scripts/gen-licenses.py from cargo metadata (%d packages).\n" % len(rows))
        o.write("The program's own licence is in LICENSE. Fonts, word lists and the OCR model are described in THIRD_PARTY_LICENSES.md and LEXICONS-NOTICE.md.\n\n")
        o.write("=" * 78 + "\nSUMMARY\n" + "=" * 78 + "\n")
        for p, d, files in rows:
            o.write("%s %s  [%s]  %s\n" % (p["name"], p["version"], p.get("license") or p.get("license_file") or "no licence field", p.get("repository") or ""))
        if missing:
            o.write("\n" + "=" * 78 + "\nNo licence file shipped in the package (the licence field above is the only statement)\n" + "=" * 78 + "\n")
            for p in missing:
                o.write("%s %s  [%s]\n" % (p["name"], p["version"], p.get("license")))
        # standard texts for crates that name MIT / Apache-2.0 but ship no file (the copyright holders are then only
        # in each package's repository, listed above)
        def first(name):
            for p, d, files in rows:
                for f in files:
                    if os.path.basename(f).upper().startswith(name):
                        return open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
            return None
        apache, mit = first("LICENSE-APACHE"), first("LICENSE-MIT")
        if missing and (apache or mit):
            o.write("\n" + "=" * 78 + "\nSTANDARD TEXTS for the packages above that ship no licence file\n" + "=" * 78 + "\n")
            if mit:
                lines = [l for l in mit.splitlines() if not l.lower().startswith("copyright")]
                o.write("\nMIT licence (copyright holders: the authors named in each package's repository)\n" + "\n".join(lines) + "\n")
            if apache:
                o.write("\nApache License 2.0\n" + apache + "\n")
        seen = {}
        o.write("\n" + "=" * 78 + "\nTEXTS\n" + "=" * 78 + "\n")
        for p, d, files in rows:
            for f in files:
                try:
                    txt = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
                except OSError:
                    continue
                key = txt
                if key in seen:
                    o.write("\n--- %s %s: %s (same text as %s)\n" % (p["name"], p["version"], f, seen[key]))
                    continue
                seen[key] = "%s %s %s" % (p["name"], p["version"], f)
                o.write("\n--- %s %s: %s\n%s\n" % (p["name"], p["version"], f, txt))
    print("%s: %d packages, %d without a licence file" % (a.out, len(rows), len(missing)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

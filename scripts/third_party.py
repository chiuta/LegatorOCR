#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_LICENSES.md from Cargo.lock (all platforms' dependencies)."""
import json, subprocess, sys
m = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"]))
ws = set(m["workspace_members"])
rows = sorted({(p["name"], p["version"], p.get("license") or "see crate", p.get("repository") or "")
               for p in m["packages"] if p["id"] not in ws})
out = ['# Third-party software\n',
       'LegatorOCR itself is MIT-licensed (see `LICENSE`). It is built from the Rust crates below, each under',
       'its own licence (the choice in an `OR` expression is yours).\n',
       '**Fonts in the graphical interface** (`epaint_default_fonts` 0.37, part of egui; crate licence expression',
       '`(MIT OR Apache-2.0) AND OFL-1.1 AND Ubuntu-font-1.0`): Hack (MIT; contains DejaVu-derived parts in the public domain',
       'and Bitstream Vera Sans Mono under the Bitstream Vera licence), Ubuntu Light (Ubuntu Font Licence 1.0), Noto Emoji',
       '(SIL OFL 1.1) and emoji-icon-font by John Slegers with its subset `egui-icons` (MIT). The command-line program embeds',
       "no font; PDFs use a glyph-less font and an sRGB profile generated by the program's own code.\n",
       '**Optical character recognition** uses either the built-in native engine (`legatorocr-nocr`, MIT, own code) or the',
       'separately installed **Tesseract** program (Apache-2.0; its language data, `tessdata`, is also Apache-2.0); nothing from',
       "Tesseract is linked or bundled. The native engine's model (`crates/legatorocr-nocr/models/multi.lnm`, compiled in) was",
       'trained on synthetic text lines and then fine-tuned on real scanned lines (a magazine and a 1960 textbook; labels from an',
       "ABBYY text layer and from agreement between Tesseract's output and the model; the scans are not in this repository). The",
       'synthetic lines were rendered from these fonts, none of which is embedded: DejaVu (Bitstream Vera licence), Liberation',
       '(SIL OFL 1.1), GNU FreeFont (GPL-3+ with font exception), Carlito (SIL OFL 1.1), Caladea (Apache-2.0), Inter (SIL OFL 1.1),',
       'URW base35 - C059, Nimbus Roman, P052, URW Bookman, Nimbus Sans (AGPL-3 with font exception), TeX Gyre and Latin Modern',
       '(GUST Font License), GFS Baskerville (SIL OFL 1.1) and Lora (SIL OFL 1.1). The word lists (`crates/legatorocr-nocr/lexicons`)',
       'derive from the `wordfreq` data by Robyn Speer and are licensed **CC BY-SA 4.0** — see `LEXICONS-NOTICE.md` (in the release',
       'archives; `crates/legatorocr-nocr/lexicons/README.md` in the source), which also says that the model was trained on text',
       'sampled from those lists and that the licence consequence for the weights is not settled.\n',
       '**Training aids, not in the binaries**: `tools/ocr-train/romanian_head/*.npz` are output layers trained on top of the',
       'docTR / OnnxTR CRNN recognisers (Apache-2.0, Mindee and Felix Dittrich; the original weights are not included, the new',
       'layers started from their values); see `docs/audit/assets-licences.md` for the full list of non-Rust assets, their sources',
       'and the open licensing questions.\n',
       "| Crate | Version | Licence |", "|---|---|---|"]
out += [f"| {n} | {v} | {l} |" for n, v, l, _ in rows]
open("THIRD_PARTY_LICENSES.md", "w").write("\n".join(out) + "\n")
print(len(rows), "crates", file=sys.stderr)

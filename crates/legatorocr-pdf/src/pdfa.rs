//! Building blocks for PDF/A-2b output: an sRGB output-intent profile, a glyph-less
//! TrueType font to embed for the invisible OCR text layer, and the XMP packet.
//!
//! All three are generated here from first principles (ICC.1 v2 and OpenType table layouts,
//! the sRGB primaries and transfer curve), so nothing third-party is bundled.

fn s15(v: f64) -> [u8; 4] {
    ((v * 65536.0).round() as i32).to_be_bytes()
}

fn pad4(v: &mut Vec<u8>) {
    while !v.len().is_multiple_of(4) {
        v.push(0);
    }
}

/// A minimal ICC v2 display profile for sRGB (matrix/TRC model, D50 PCS).
pub fn srgb_icc() -> Vec<u8> {
    let text = |s: &str| -> Vec<u8> {
        let mut v = b"text\0\0\0\0".to_vec();
        v.extend_from_slice(s.as_bytes());
        v.push(0);
        v
    };
    let desc = {
        let name = b"sRGB IEC61966-2.1 (LegatorOCR)\0";
        let mut v = b"desc\0\0\0\0".to_vec();
        v.extend((name.len() as u32).to_be_bytes());
        v.extend_from_slice(name);
        v.extend([0u8; 8]); // Unicode language code + count
        v.extend([0u8; 3]); // ScriptCode code + count
        v.extend([0u8; 67]);
        v
    };
    let xyz = |x: f64, y: f64, z: f64| -> Vec<u8> {
        let mut v = b"XYZ \0\0\0\0".to_vec();
        v.extend(s15(x));
        v.extend(s15(y));
        v.extend(s15(z));
        v
    };
    let curve = {
        let n = 1024usize;
        let mut v = b"curv\0\0\0\0".to_vec();
        v.extend((n as u32).to_be_bytes());
        for i in 0..n {
            let c = i as f64 / (n - 1) as f64;
            let l = if c <= 0.04045 {
                c / 12.92
            } else {
                ((c + 0.055) / 1.055).powf(2.4)
            };
            v.extend(((l * 65535.0).round() as u16).to_be_bytes());
        }
        v
    };
    let tags: Vec<(&[u8; 4], Vec<u8>)> = vec![
        (b"desc", desc),
        (b"cprt", text("Public domain, generated by LegatorOCR")),
        (b"wtpt", xyz(0.9642, 1.0, 0.8249)),
        (b"rXYZ", xyz(0.4360, 0.2225, 0.0139)),
        (b"gXYZ", xyz(0.3851, 0.7169, 0.0971)),
        (b"bXYZ", xyz(0.1431, 0.0606, 0.7141)),
        (b"rTRC", curve),
    ];
    let n_tags = tags.len() + 2; // gTRC and bTRC share rTRC's data
    let mut body = Vec::new();
    let mut table = Vec::new();
    let base = 128 + 4 + 12 * n_tags;
    let mut curve_at = (0usize, 0usize);
    for (sig, mut data) in tags {
        let len = data.len();
        pad4(&mut data);
        let at = base + body.len();
        table.extend_from_slice(sig);
        table.extend((at as u32).to_be_bytes());
        table.extend((len as u32).to_be_bytes());
        if sig == b"rTRC" {
            curve_at = (at, len);
        }
        body.extend(data);
    }
    for sig in [b"gTRC", b"bTRC"] {
        table.extend_from_slice(sig);
        table.extend((curve_at.0 as u32).to_be_bytes());
        table.extend((curve_at.1 as u32).to_be_bytes());
    }
    let total = base + body.len();
    let mut h = Vec::with_capacity(total);
    h.extend((total as u32).to_be_bytes());
    h.extend([0u8; 4]); // preferred CMM
    h.extend([2, 0x10, 0, 0]); // version 2.1
    h.extend_from_slice(b"mntr");
    h.extend_from_slice(b"RGB ");
    h.extend_from_slice(b"XYZ ");
    for v in [2026u16, 1, 1, 0, 0, 0] {
        h.extend(v.to_be_bytes());
    }
    h.extend_from_slice(b"acsp");
    h.extend([0u8; 4]); // platform
    h.extend([0u8; 4]); // flags
    h.extend([0u8; 4]); // manufacturer
    h.extend([0u8; 4]); // model
    h.extend([0u8; 8]); // attributes
    h.extend([0u8; 4]); // rendering intent: perceptual
    h.extend(s15(0.9642));
    h.extend(s15(1.0));
    h.extend(s15(0.8249));
    h.extend([0u8; 4]); // creator
    h.extend([0u8; 44]); // profile ID + reserved
    debug_assert_eq!(h.len(), 128);
    h.extend((n_tags as u32).to_be_bytes());
    h.extend(table);
    h.extend(body);
    h
}

fn table_checksum(d: &[u8]) -> u32 {
    let mut s = 0u32;
    for c in d.chunks(4) {
        let mut b = [0u8; 4];
        b[..c.len()].copy_from_slice(c);
        s = s.wrapping_add(u32::from_be_bytes(b));
    }
    s
}

/// A TrueType font with `n_glyphs` glyphs, 1000 units/em and every advance 500, whose only
/// outline is a box in `.notdef`. Used as the (invisible) text font, so that the file embeds
/// every font it uses.
pub fn glyphless_ttf(n_glyphs: usize) -> Vec<u8> {
    let n = n_glyphs.clamp(1, 65_535);
    let be16 = |v: u16| v.to_be_bytes();
    let bei16 = |v: i16| v.to_be_bytes();
    // glyf: .notdef rectangle (50,0)-(450,800)
    let mut glyf = Vec::new();
    glyf.extend(bei16(1)); // contours
    glyf.extend(bei16(50));
    glyf.extend(bei16(0));
    glyf.extend(bei16(450));
    glyf.extend(bei16(800));
    glyf.extend(be16(3)); // end point
    glyf.extend(be16(0)); // instructions
    glyf.extend([1u8; 4]); // on-curve, 16-bit deltas
    for dx in [50i16, 400, 0, -400] {
        glyf.extend(bei16(dx));
    }
    for dy in [0i16, 0, 800, 0] {
        glyf.extend(bei16(dy));
    }
    pad4(&mut glyf);
    let mut loca = Vec::with_capacity((n + 1) * 2);
    loca.extend(be16(0));
    for _ in 0..n {
        loca.extend(be16((glyf.len() / 2) as u16));
    }
    let mut head = Vec::new();
    head.extend([0, 1, 0, 0]); // version
    head.extend([0, 1, 0, 0]); // revision
    head.extend([0u8; 4]); // checksum adjustment, patched below
    head.extend(0x5F0F_3CF5u32.to_be_bytes());
    head.extend(be16(0)); // flags
    head.extend(be16(1000));
    head.extend(3_850_070_400u64.to_be_bytes()); // created (2026-01-01)
    head.extend(3_850_070_400u64.to_be_bytes()); // modified
    head.extend(bei16(0));
    head.extend(bei16(0));
    head.extend(bei16(500));
    head.extend(bei16(1000));
    head.extend(be16(0)); // macStyle
    head.extend(be16(8)); // lowestRecPPEM
    head.extend(bei16(2)); // direction hint
    head.extend(bei16(0)); // short loca
    head.extend(bei16(0));
    let mut hhea = Vec::new();
    hhea.extend([0, 1, 0, 0]);
    hhea.extend(bei16(1000));
    hhea.extend(bei16(0));
    hhea.extend(bei16(0));
    hhea.extend(be16(500));
    hhea.extend(bei16(0));
    hhea.extend(bei16(0));
    hhea.extend(bei16(500));
    hhea.extend(bei16(1));
    hhea.extend(bei16(0));
    hhea.extend(bei16(0));
    hhea.extend([0u8; 8]);
    hhea.extend(bei16(0));
    hhea.extend(be16(1)); // one long metric, the rest share its advance
    let mut maxp = Vec::new();
    maxp.extend([0, 1, 0, 0]);
    maxp.extend(be16(n as u16));
    maxp.extend(be16(4)); // points
    maxp.extend(be16(1)); // contours
    maxp.extend([0u8; 4]); // composite points / contours
    maxp.extend(be16(1)); // maxZones
    maxp.extend([0u8; 16]);
    let mut hmtx = Vec::new();
    hmtx.extend(be16(500));
    hmtx.extend(bei16(0));
    hmtx.extend(vec![0u8; (n - 1) * 2]);
    // cmap: format 4, only the terminating segment
    let mut cmap = Vec::new();
    cmap.extend(be16(0));
    cmap.extend(be16(1));
    cmap.extend(be16(3));
    cmap.extend(be16(1));
    cmap.extend(12u32.to_be_bytes());
    cmap.extend(be16(4));
    cmap.extend(be16(24));
    cmap.extend(be16(0));
    cmap.extend(be16(2)); // segCountX2
    cmap.extend(be16(2));
    cmap.extend(be16(0));
    cmap.extend(be16(0));
    cmap.extend(be16(0xFFFF)); // end
    cmap.extend(be16(0)); // pad
    cmap.extend(be16(0xFFFF)); // start
    cmap.extend(be16(1)); // delta
    cmap.extend(be16(0)); // range offset
    let mut name = Vec::new();
    let names: [(u16, &str); 4] = [
        (1, "GlyphLessFont"),
        (2, "Regular"),
        (4, "GlyphLessFont"),
        (6, "GlyphLessFont"),
    ];
    name.extend(be16(0));
    name.extend(be16(names.len() as u16));
    name.extend(be16((6 + 12 * names.len()) as u16));
    let mut strings = Vec::new();
    for (id, s) in names {
        let u: Vec<u8> = s.encode_utf16().flat_map(|c| c.to_be_bytes()).collect();
        name.extend(be16(3));
        name.extend(be16(1));
        name.extend(be16(0x0409));
        name.extend(be16(id));
        name.extend(be16(u.len() as u16));
        name.extend(be16(strings.len() as u16));
        strings.extend(u);
    }
    name.extend(strings);
    let mut post = vec![0, 3, 0, 0];
    post.extend([0u8; 28]);
    let mut os2 = Vec::new();
    os2.extend(be16(0)); // version
    os2.extend(bei16(500));
    os2.extend(be16(400));
    os2.extend(be16(5));
    os2.extend(be16(0)); // fsType: installable embedding
    for v in [0i16, 0, 0, 0, 0, 0, 0, 0, 0, 0] {
        os2.extend(bei16(v));
    }
    os2.extend(bei16(0)); // family class
    os2.extend([0u8; 10]); // panose
    os2.extend([0u8; 16]); // unicode ranges
    os2.extend_from_slice(b"NONE");
    os2.extend(be16(0x40)); // regular
    os2.extend(be16(0));
    os2.extend(be16(0xFFFF));
    os2.extend(bei16(800));
    os2.extend(bei16(0));
    os2.extend(bei16(200));
    os2.extend(be16(1000));
    os2.extend(be16(0));
    let mut tables: Vec<(&[u8; 4], Vec<u8>)> = vec![
        (b"OS/2", os2),
        (b"cmap", cmap),
        (b"glyf", glyf),
        (b"head", head),
        (b"hhea", hhea),
        (b"hmtx", hmtx),
        (b"loca", loca),
        (b"maxp", maxp),
        (b"name", name),
        (b"post", post),
    ];
    tables.sort_by_key(|t| *t.0);
    let nt = tables.len();
    let mut out = Vec::new();
    out.extend([0, 1, 0, 0]);
    out.extend(be16(nt as u16));
    let mut sr = 1u16;
    let mut es = 0u16;
    while sr * 2 <= nt as u16 {
        sr *= 2;
        es += 1;
    }
    out.extend(be16(sr * 16));
    out.extend(be16(es));
    out.extend(be16(nt as u16 * 16 - sr * 16));
    let off = 12 + 16 * nt;
    let mut head_at = 0;
    let mut dir = Vec::new();
    let mut data = Vec::new();
    for (tag, t) in &tables {
        if *tag == b"head" {
            head_at = off + data.len();
        }
        dir.extend_from_slice(*tag);
        dir.extend(table_checksum(t).to_be_bytes());
        dir.extend(((off + data.len()) as u32).to_be_bytes());
        dir.extend((t.len() as u32).to_be_bytes());
        data.extend_from_slice(t);
        pad4(&mut data);
    }
    out.extend(dir);
    out.extend(data);
    let whole = table_checksum(&out);
    let adj = 0xB1B0_AFBAu32.wrapping_sub(whole);
    out[head_at + 8..head_at + 12].copy_from_slice(&adj.to_be_bytes());
    out
}

fn esc(s: &str) -> String {
    // XML 1.0 forbids most control characters and U+FFFE/FFFF: drop them so the packet stays well-formed
    let clean: String = s
        .chars()
        .filter(|&c| {
            matches!(c, '\t' | '\n' | '\r') || (c >= ' ' && c != '\u{FFFE}' && c != '\u{FFFF}')
        })
        .collect();
    clean
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// `D:YYYYMMDDHHmmSSZ` → `YYYY-MM-DDTHH:mm:SSZ`.
pub fn xmp_date(pdf_date: &str) -> String {
    let d = pdf_date.trim_start_matches("D:");
    format!(
        "{}-{}-{}T{}:{}:{}Z",
        &d[0..4],
        &d[4..6],
        &d[6..8],
        &d[8..10],
        &d[10..12],
        &d[12..14]
    )
}

/// The XMP packet (PDF/A-2b identification plus the Info-dictionary values).
pub struct Xmp<'a> {
    pub title: Option<&'a str>,
    pub author: Option<&'a str>,
    pub subject: Option<&'a str>,
    pub keywords: Option<&'a str>,
    pub rights: Option<&'a str>,
    pub producer: &'a str,
    /// `D:...Z` date for creation and modification.
    pub date: Option<&'a str>,
}

impl Xmp<'_> {
    pub fn render(&self) -> String {
        let mut s = String::from(
            "<?xpacket begin=\"\u{FEFF}\" id=\"W5M0MpCehiHzreSzNTczkc9d\"?>\n\
             <x:xmpmeta xmlns:x=\"adobe:ns:meta/\">\n\
             <rdf:RDF xmlns:rdf=\"http://www.w3.org/1999/02/22-rdf-syntax-ns#\">\n\
             <rdf:Description rdf:about=\"\" xmlns:pdfaid=\"http://www.aiim.org/pdfa/ns/id/\">\
             <pdfaid:part>2</pdfaid:part><pdfaid:conformance>B</pdfaid:conformance>\
             </rdf:Description>\n",
        );
        let alt = |t: &str| {
            format!(
                "<rdf:Alt><rdf:li xml:lang=\"x-default\">{}</rdf:li></rdf:Alt>",
                esc(t)
            )
        };
        let mut dc = String::new();
        if let Some(t) = self.title {
            dc.push_str(&format!("<dc:title>{}</dc:title>", alt(t)));
        }
        if let Some(a) = self.author {
            dc.push_str(&format!(
                "<dc:creator><rdf:Seq><rdf:li>{}</rdf:li></rdf:Seq></dc:creator>",
                esc(a)
            ));
        }
        if let Some(t) = self.subject {
            dc.push_str(&format!("<dc:description>{}</dc:description>", alt(t)));
        }
        if let Some(t) = self.rights {
            dc.push_str(&format!("<dc:rights>{}</dc:rights>", alt(t)));
        }
        if !dc.is_empty() {
            s.push_str(&format!(
                "<rdf:Description rdf:about=\"\" xmlns:dc=\"http://purl.org/dc/elements/1.1/\">{dc}</rdf:Description>\n"
            ));
        }
        s.push_str(&format!(
            "<rdf:Description rdf:about=\"\" xmlns:pdf=\"http://ns.adobe.com/pdf/1.3/\">\
             <pdf:Producer>{}</pdf:Producer>{}</rdf:Description>\n",
            esc(self.producer),
            self.keywords
                .map(|k| format!("<pdf:Keywords>{}</pdf:Keywords>", esc(k)))
                .unwrap_or_default()
        ));
        let dates = self
            .date
            .map(|d| {
                let d = xmp_date(d);
                format!("<xmp:CreateDate>{d}</xmp:CreateDate><xmp:ModifyDate>{d}</xmp:ModifyDate>")
            })
            .unwrap_or_default();
        s.push_str(&format!(
            "<rdf:Description rdf:about=\"\" xmlns:xmp=\"http://ns.adobe.com/xap/1.0/\">\
             <xmp:CreatorTool>{}</xmp:CreatorTool>{dates}</rdf:Description>\n\
             </rdf:RDF>\n</x:xmpmeta>\n<?xpacket end=\"w\"?>",
            esc(self.producer)
        ));
        s
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn icc_header_is_consistent() {
        let p = srgb_icc();
        assert_eq!(
            u32::from_be_bytes(p[0..4].try_into().unwrap()) as usize,
            p.len()
        );
        assert_eq!(&p[36..40], b"acsp");
        assert_eq!(&p[12..16], b"mntr");
        assert_eq!(p.len() % 4, 0);
    }

    #[test]
    fn font_checksums_add_up() {
        let f = glyphless_ttf(300);
        assert_eq!(table_checksum(&f), 0xB1B0_AFBA);
        assert_eq!(&f[0..4], &[0, 1, 0, 0]);
    }

    #[test]
    fn xmp_dates() {
        assert_eq!(xmp_date("D:20261031120005Z"), "2026-10-31T12:00:05Z");
    }
}
